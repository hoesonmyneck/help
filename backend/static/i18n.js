// Один и тот же вид помощи приходит и из БД («Социальная помощь …»), и из
// справочника («СОЦИАЛЬНАЯ ПОМОЩЬ …») — ищем без учёта регистра.
// ключ нормализуем: trim + lowercase (в словаре встречаются ключи с
// хвостовым пробелом, напр. 'Утвержденные виды помощи в МИО ')
const _KKlc = Object.create(null);
for (const k in KK) _KKlc[k.trim().toLowerCase()] = KK[k];

/** Найти перевод (регистронезависимо). undefined — перевода нет. */
function _lookup(s) {
  if (s == null) return undefined;
  const k = String(s).trim();
  if (KK[k] !== undefined) return KK[k];
  return _KKlc[k.toLowerCase()];
}

let LANG = localStorage.getItem('lang') === 'kk' ? 'kk' : 'ru';

/** Перевести строку. На русском — как есть. Неизвестное — как есть. */
function t(s) {
  if (LANG !== 'kk' || s == null) return s;
  const v = _lookup(s);
  return v === undefined ? s : v;
}

